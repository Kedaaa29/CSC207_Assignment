
#include <iostream>
using namespace std;

int main() {
    int number1 = 22;
    int number2 = 57;
    
    if (number1 % 2 == 0) {
        cout << number1 << " is Even." << endl;
    }
    else {
        cout << number1 << " is Odd." << endl;
    }

    if (number2 % 2 == 0) {
        cout << number2 << " is Even." << endl;
    }
    else {
        cout << number2 << " is Odd." << endl;
    }

    return 0;
}
